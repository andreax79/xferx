C	THIS PROGRAM CALCULATES IX FACTORIAL FOR GIVEN IX
5	WRITE 2, 100
10	READ 1, 200, IX
	IFACT = IY = 1
	IF (IX) 5, 32, 30
30	IF (IX-IY) 41, 32, 33
32	WRITE 2, 300, IX, IFACT
	GO TO 10
33	IFACT = IFACT * (IY = IY + 1)
	GO TO 30
41	PAUSE 7777
	GO TO 5
100	FORMAT (/30H PLEASE TYPE A POSITIVE NUMBER/)
200	FORMAT (I4)
300	FORMAT (/I4, 13H FACTORIAL IS, I7/)
	END
